import {readFile,writeFile,readdir,stat,mkdir} from 'node:fs/promises';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {fileURLToPath} from 'node:url';
import {backgrounds} from '../story.js';
import {withOrientedPhoto} from './photo-source.mjs';

const run=promisify(execFile),root=new URL('../',import.meta.url);
const path=name=>fileURLToPath(new URL(name,root));
const manifest=JSON.parse(await readFile(path('asset-manifest.json'),'utf8'));
const map=JSON.parse(await readFile(path('photo-map.json'),'utf8'));
let originals=[];
try{originals=await readdir(path('图片/'));}catch{}
await mkdir(path('assets/photos/'),{recursive:true});
let before=0,desktop=0,mobile=0;
for(const key of new Set(Object.values(backgrounds))){
  if(!map[key])continue;
  const reference=map[key];
  const name=originals.find(name=>typeof reference==='number'?name.includes('_'+reference+'_'):name===reference);
  const source=name?path('图片/'+name):path('assets/photos/'+key+'.jpg');
  const originalSize=(await stat(source)).size;
  await withOrientedPhoto(source,async normalized=>{
  for(const [suffix,edge,quality] of [['bg',2560,80],['mobile',1280,78]]){
    // Limit the long edge, preserve composition, and never upscale small originals.
    const {stdout}=await run('sips',['-g','pixelWidth','-g','pixelHeight',normalized]);
    const width=Number(stdout.match(/pixelWidth: (\d+)/)[1]),height=Number(stdout.match(/pixelHeight: (\d+)/)[1]);
    const resize=Math.max(width,height)>edge?(width>=height?[String(edge),'0']:['0',String(edge)]):[String(width),String(height)];
    const output=`assets/photos/${key}.${suffix}.webp`;
    await run('cwebp',['-quiet','-q',String(quality),'-m','6','-metadata','icc','-resize',...resize,normalized,'-o',path(output)]);
    manifest[suffix==='bg'?key:'mobile_'+key]=output;
    if(suffix==='bg')desktop+=(await stat(path(output))).size;
    else mobile+=(await stat(path(output))).size;
  }
  });
  before+=originalSize;
}
await writeFile(path('asset-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
// The bundled map keeps the game usable even if the runtime manifest request fails.
await writeFile(path('assets-default.js'),'// Generated by scripts/optimize-backgrounds.mjs\nexport const defaultAssets = '+JSON.stringify(manifest,null,2)+';\n');
console.log(`背景：原图 ${(before/1048576).toFixed(2)} MB → 桌面 ${(desktop/1048576).toFixed(2)} MB / 手机 ${(mobile/1048576).toFixed(2)} MB`);
